#!/usr/bin/env python3
"""Generate the DepthVibe DV launcher and desktop icons using only Python stdlib."""
from __future__ import annotations

import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASTER_SIZE = 512


def inside_polygon(x: float, y: float, points: list[tuple[int, int]]) -> bool:
    inside = False
    previous = len(points) - 1
    for current in range(len(points)):
        xi, yi = points[current]
        xj, yj = points[previous]
        if (yi > y) != (yj > y):
            crossing = (xj - xi) * (y - yi) / ((yj - yi) or 1e-9) + xi
            if x < crossing:
                inside = not inside
        previous = current
    return inside


def inside_rounded_rect(x: int, y: int, radius: int = 112) -> bool:
    left = top = 18
    right = bottom = MASTER_SIZE - 18
    cx = min(max(x, left + radius), right - radius)
    cy = min(max(y, top + radius), bottom - radius)
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2 or (
        left + radius <= x <= right - radius
        and top <= y <= bottom
    ) or (
        left <= x <= right
        and top + radius <= y <= bottom - radius
    )


def mix(a: tuple[int, int, int], b: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    t = max(0.0, min(1.0, t))
    return tuple(round(a[i] * (1.0 - t) + b[i] * t) for i in range(3))


def gradient(x: int, y: int) -> tuple[int, int, int]:
    t = max(0.0, min(1.0, (x / MASTER_SIZE) * 0.62 + (y / MASTER_SIZE) * 0.38))
    if t < 0.54:
        return mix((119, 139, 255), (177, 116, 244), t / 0.54)
    return mix((177, 116, 244), (88, 221, 208), (t - 0.54) / 0.46)


def make_icon() -> bytes:
    pixels = bytearray(MASTER_SIZE * MASTER_SIZE * 4)
    # A bold geometric DV monogram built as vector-like polygons.
    d_outer = [
        (86, 132), (170, 132), (222, 146), (266, 190),
        (285, 251), (266, 312), (222, 356), (170, 372), (86, 372),
    ]
    d_inner = [
        (145, 199), (169, 199), (207, 211), (225, 251),
        (207, 293), (169, 305), (145, 305),
    ]
    v_shape = [
        (273, 132), (337, 132), (379, 264), (424, 132),
        (487, 132), (419, 379), (350, 379),
    ]

    for y in range(MASTER_SIZE):
        row = y * MASTER_SIZE * 4
        for x in range(MASTER_SIZE):
            if not inside_rounded_rect(x, y):
                continue
            offset = row + x * 4
            # Deep navy panel with a slight diagonal lift.
            t = (x + y) / (2 * MASTER_SIZE)
            base = mix((9, 13, 25), (22, 28, 49), t)
            is_border = not inside_rounded_rect(x, y, 108)
            colour = (83, 101, 157) if is_border else base

            d_mark = inside_polygon(x, y, d_outer) and not inside_polygon(x, y, d_inner)
            v_mark = inside_polygon(x, y, v_shape)
            if d_mark or v_mark:
                colour = gradient(x, y)
            # A small accent glint along the top edge.
            if 75 < x < 430 and 38 < y < 43:
                colour = mix(colour, (124, 153, 255), 0.22)

            pixels[offset:offset + 4] = bytes((*colour, 255))

    return encode_png(MASTER_SIZE, MASTER_SIZE, bytes(pixels))


def png_chunk(tag: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)


def encode_png(width: int, height: int, rgba: bytes) -> bytes:
    stride = width * 4
    raw = b"".join(b"\x00" + rgba[y * stride:(y + 1) * stride] for y in range(height))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", ihdr)
        + png_chunk(b"IDAT", zlib.compress(raw, 9))
        + png_chunk(b"IEND", b"")
    )


def decode_png_rgba(data: bytes) -> tuple[int, int, bytearray]:
    # The icon file is generated by this script, so its PNG is known to use
    # filter type 0, RGBA, 8-bit channels and a single zlib stream.
    cursor = 8
    width = height = 0
    compressed = bytearray()
    while cursor < len(data):
        length = struct.unpack(">I", data[cursor:cursor + 4])[0]
        tag = data[cursor + 4:cursor + 8]
        chunk = data[cursor + 8:cursor + 8 + length]
        cursor += 12 + length
        if tag == b"IHDR":
            width, height = struct.unpack(">II", chunk[:8])
        elif tag == b"IDAT":
            compressed.extend(chunk)
        elif tag == b"IEND":
            break
    raw = zlib.decompress(bytes(compressed))
    stride = width * 4
    rgba = bytearray(width * height * 4)
    source = 0
    for y in range(height):
        filter_type = raw[source]
        source += 1
        if filter_type != 0:
            raise ValueError("Unexpected generated PNG filter.")
        start = y * stride
        rgba[start:start + stride] = raw[source:source + stride]
        source += stride
    return width, height, rgba


def resize_rgba(source: bytearray, source_size: int, target_size: int) -> bytes:
    if target_size == source_size:
        return bytes(source)
    output = bytearray(target_size * target_size * 4)
    for y in range(target_size):
        sy = min(source_size - 1, (y * source_size) // target_size)
        for x in range(target_size):
            sx = min(source_size - 1, (x * source_size) // target_size)
            src = (sy * source_size + sx) * 4
            dst = (y * target_size + x) * 4
            output[dst:dst + 4] = source[src:src + 4]
    return bytes(output)


def write_resized_png(master: bytearray, target_size: int, path: Path) -> None:
    rgba = resize_rgba(master, MASTER_SIZE, target_size)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encode_png(target_size, target_size, rgba))


def make_ico(png: bytes, path: Path) -> None:
    # PNG-compressed 256px icon frames are supported by modern Windows.
    entry = struct.pack(
        "<BBBBHHII",
        0, 0, 0, 0, 1, 32, len(png), 22,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(struct.pack("<HHH", 0, 1, 1) + entry + png)



def generate_android_adaptive_icons(master: bytearray, resource_root: Path) -> None:
    """Create a safe-zone foreground and adaptive icon for Android 8+."""
    target = 432
    foreground_size = 300
    foreground = bytearray(target * target * 4)
    resized = resize_rgba(master, MASTER_SIZE, foreground_size)
    offset = (target - foreground_size) // 2
    for y in range(foreground_size):
        source_start = y * foreground_size * 4
        target_start = ((y + offset) * target + offset) * 4
        foreground[target_start:target_start + foreground_size * 4] = (
            resized[source_start:source_start + foreground_size * 4]
        )

    drawable = resource_root / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_foreground.png").write_bytes(
        encode_png(target, target, bytes(foreground))
    )

    values = resource_root / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_background.xml").write_text(
        '<resources>\n'
        '    <color name="ic_launcher_background">#090D19</color>\n'
        '</resources>\n',
        encoding="utf-8",
    )

    adaptive = resource_root / "mipmap-anydpi-v26"
    adaptive.mkdir(parents=True, exist_ok=True)
    (adaptive / "ic_launcher.xml").write_text(
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n',
        encoding="utf-8",
    )


def generate_linux_icons(master: bytearray, directory: Path) -> None:
    for size in (16, 24, 32, 48, 64, 128, 256, 512):
        write_resized_png(
            master,
            size,
            directory / f"{size}x{size}" / "apps" / "depthvibe.png",
        )

def generate_ios_icons(master: bytearray, directory: Path) -> None:
    sizes = [
        ("20x20", "2x", 40), ("20x20", "3x", 60),
        ("29x29", "2x", 58), ("29x29", "3x", 87),
        ("40x40", "2x", 80), ("40x40", "3x", 120),
        ("60x60", "2x", 120), ("60x60", "3x", 180),
        ("76x76", "1x", 76), ("76x76", "2x", 152),
        ("83.5x83.5", "2x", 167), ("1024x1024", "1x", 1024),
    ]
    images = []
    for logical, scale, pixel_size in sizes:
        filename = f"DepthVibe-{pixel_size}.png"
        write_resized_png(master, pixel_size, directory / filename)
        idiom = (
            "ios-marketing" if logical == "1024x1024"
            else "ipad" if logical in ("76x76", "83.5x83.5")
            else "iphone"
        )
        images.append({
            "filename": filename,
            "idiom": idiom,
            "platform": "ios",
            "size": logical,
            "scale": scale,
        })
    (directory / "Contents.json").write_text(
        json.dumps({"images": images, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
        encoding="utf-8",
    )


def generate_macos_icons(master: bytearray, directory: Path) -> None:
    sizes = [(16, 1), (16, 2), (32, 1), (32, 2), (128, 1), (128, 2), (256, 1), (256, 2), (512, 1), (512, 2)]
    images = []
    for logical, scale in sizes:
        pixel_size = logical * scale
        filename = f"DepthVibe-{logical}x{logical}@{scale}x.png"
        write_resized_png(master, pixel_size, directory / filename)
        images.append({
            "filename": filename,
            "idiom": "mac",
            "scale": f"{scale}x",
            "size": f"{logical}x{logical}",
        })
    (directory / "Contents.json").write_text(
        json.dumps({"images": images, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    master_png = make_icon()
    width, height, master = decode_png_rgba(master_png)
    assert width == MASTER_SIZE and height == MASTER_SIZE

    asset = ROOT / "assets" / "branding" / "depthvibe_icon.png"
    asset.parent.mkdir(parents=True, exist_ok=True)
    asset.write_bytes(master_png)

    for density, pixels in [
        ("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
        ("xxhdpi", 144), ("xxxhdpi", 192),
    ]:
        write_resized_png(
            master,
            pixels,
            ROOT / "android" / "app" / "src" / "main" / "res" /
            f"mipmap-{density}" / "ic_launcher.png",
        )

    generate_android_adaptive_icons(
        master,
        ROOT / "android" / "app" / "src" / "main" / "res",
    )

    windows_icon = ROOT / "windows" / "runner" / "resources" / "app_icon.ico"
    windows_png = encode_png(256, 256, resize_rgba(master, MASTER_SIZE, 256))
    make_ico(windows_png, windows_icon)

    generate_ios_icons(
        master,
        ROOT / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset",
    )
    generate_macos_icons(
        master,
        ROOT / "macos" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset",
    )

    generate_linux_icons(
        master,
        ROOT / "linux" / "icons" / "hicolor",
    )
    print("Generated DepthVibe DV launcher and desktop icons.")


if __name__ == "__main__":
    main()
